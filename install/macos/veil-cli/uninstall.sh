#!/bin/bash
set -euo pipefail
#
# ⚠️  이 스크립트의 실행으로 발생하는 모든 결과에 대한
#     귀책사유는 실행자 본인에게 있습니다.

# veil-cli uninstaller for macOS
#
# Usage:
#   bash install/macos/veil-cli/uninstall.sh

echo "=== veil-cli uninstaller ==="
echo ""

echo "[1/2] Removing npm package..."
npm uninstall -g veilkey-cli 2>/dev/null || true
echo "  Removed."

CONFIG_DIR="${VEILKEY_CONFIG_DIR:-$HOME/.veilkey}"
ENV_FILE="$CONFIG_DIR/env"
echo "[2/2] Cleaning installer-generated environment file..."
if [ -f "$ENV_FILE" ] && [ ! -L "$ENV_FILE" ] && grep -Fxq '# Generated by VeilKey CLI installer.' "$ENV_FILE"; then
    rm -f "$ENV_FILE"
    echo "  Removed $ENV_FILE (other settings preserved)."
else
    echo "  No installer-generated file at $ENV_FILE; user settings preserved."
fi
if [ -f ".veilkey/env" ]; then
    echo "  Legacy project .veilkey/env is not auto-loaded; review and remove it manually if no longer needed."
fi

echo ""
echo "=== veil-cli uninstall complete ==="
echo ""
